/**
 * Hand-scoring corpus — brief acceptance check A1.
 *
 * ≥150 vectors against the real scorer (src/scoring.ts). Every expected
 * value below was derived by hand from the standard scoring rules:
 *
 *   basic points = fu × 2^(han+2), capped at mangan (2000) for ≤5 han;
 *   haneman 6–7 han = 3000, baiman 8–10 = 4000, sanbaiman 11–12 = 6000,
 *   kazoe (13+ han) and yakuman = 8000 per multiple. Kiriage mangan OFF.
 *   Ron: ×4 (non-dealer) / ×6 (dealer). Tsumo: non-dealers pay ×1 basic,
 *   dealer pays ×2 (dealer winner: all pay ×2). Each payment rounded up
 *   to the next 100. Honba adds 300 (ron) / 100 per payer (tsumo) and is
 *   INCLUDED in the expected payments; riichi sticks are asserted
 *   separately in the test (stickPoints = sticks × 1000).
 *
 * Fu: 20 base; +10 closed ron; +2 tsumo (waived for pinfu, whose tsumo is
 * a fixed 20 fu); triplets simple 2 / terminal-or-honor 4, ×2 closed,
 * kans ×4 again; +2 yakuhai pair (a double-wind pair is +2, not +4);
 * +2 tanki/kanchan/penchan wait; total rounded up to 10, minimum 30
 * except pinfu tsumo (20) and chiitoitsu (fixed 25).
 *
 * `hand` is the COMPLETE hand in tiles.ts notation, meld tiles included;
 * `melds` lists the declared sets so open/closed is known. Winds are tile
 * type indices: 27 = East, 28 = South, 29 = West, 30 = North. Dealer is
 * seat East.
 */

import type { MeldKind } from "../src/scoring.js";

export interface ScoringVector {
  readonly id: string;
  readonly description: string;
  /** Complete hand, notation per tiles.ts parseCounts (meld tiles included). */
  readonly hand: string;
  /** Winning tile, single-tile notation, e.g. "4s". */
  readonly winningTile: string;
  readonly melds?: readonly { readonly kind: MeldKind; readonly tiles: string }[];
  readonly context: {
    readonly winType: "ron" | "tsumo";
    readonly seatWind: number;
    readonly roundWind: number;
    readonly riichi: boolean;
    readonly doubleRiichi?: boolean;
    readonly ippatsu?: boolean;
    readonly haitei?: boolean;
    readonly houtei?: boolean;
    readonly rinshan?: boolean;
    readonly chankan?: boolean;
    readonly firstDrawTsumo?: boolean;
    readonly dora: number;
    readonly honba: number;
    readonly riichiSticks: number;
  };
  readonly expected: {
    readonly han: number;
    /** 0 where fu does not apply (yakuman, incl. kazoe). */
    readonly fu: number;
    readonly yakumanMultiple: number;
    /** Yaku ids only — dora is never a yaku. */
    readonly yaku: readonly string[];
    readonly ronPoints: number | null;
    readonly tsumoPoints: { readonly nonDealer: number; readonly dealer: number } | null;
  };
}

const E = 27;
const S = 28;
const W = 29;

type Ctx = ScoringVector["context"];
type Exp = ScoringVector["expected"];
const ctx = (c: Partial<Ctx> & Pick<Ctx, "winType">): Ctx => ({
  seatWind: S,
  roundWind: E,
  riichi: false,
  dora: 0,
  honba: 0,
  riichiSticks: 0,
  ...c,
});
const ron = (points: number): Pick<Exp, "ronPoints" | "tsumoPoints"> => ({
  ronPoints: points,
  tsumoPoints: null,
});
const tsumo = (nonDealer: number, dealer: number): Pick<Exp, "ronPoints" | "tsumoPoints"> => ({
  ronPoints: null,
  tsumoPoints: { nonDealer, dealer },
});

